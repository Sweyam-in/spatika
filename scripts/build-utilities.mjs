/**
 * Generates packages/tokens/src/utilities.css — the prebuilt utility layer for apps that
 * import @spatika/tokens/styles.css without the @spatika/utilities build plugin. It holds every
 * utility class used by Spatika React, Charts, Editor and the docs site, compiled by the same
 * engine the plugin uses, so both produce identical rules.
 *
 *   node scripts/build-utilities.mjs          write the file
 *   node scripts/build-utilities.mjs --check  exit 1 when the committed file is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { createCompiler, resolveContent, extractCandidates } = await import(
  path.join(root, "packages/utilities/dist/index.js")
);

export const SOURCES = [
  "packages/react/src/**/*.{ts,tsx}",
  "packages/charts/src/**/*.{ts,tsx}",
  "packages/editor/src/**/*.{ts,tsx}",
  "apps/website/src/**/*.{ts,tsx}",
  "apps/website/index.html",
  "!**/*.test.{ts,tsx}",
  "!**/*.spec.{ts,tsx}",
  "!apps/website/src/generated/**",
];

export function buildUtilities() {
  const { files } = resolveContent(SOURCES, root);
  const candidates = new Set();
  for (const file of files) extractCandidates(readFileSync(file, "utf8"), candidates);
  // Classes the prebuilt layer has always shipped for apps that do not run the compiler.
  const safelist = JSON.parse(readFileSync(path.join(root, "scripts/utilities-safelist.json"), "utf8"));
  const css = createCompiler().build([...candidates, ...safelist].sort());
  return `/**
 * Spatika utility layer — GENERATED by scripts/build-utilities.mjs from the classes used in
 * Spatika React, Charts, Editor and the docs site. Do not edit; run \`npm run utilities\`.
 * Apps that compile their own utilities use @spatika/utilities, which emits identical rules.
 */

${css}`;
}

export const UTILITIES_FILE = path.join(root, "packages/tokens/src/utilities.css");

if (process.argv[1] === fileURLToPath(import.meta.url)) {
const out = UTILITIES_FILE;
const next = buildUtilities();
if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== next) {
    console.error("packages/tokens/src/utilities.css is stale — run `npm run utilities`.");
    process.exit(1);
  }
  console.log("utilities.css is current");
} else {
  writeFileSync(out, next);
  console.log(`utilities.css: ${next.split("\n").length} lines`);
}
}
